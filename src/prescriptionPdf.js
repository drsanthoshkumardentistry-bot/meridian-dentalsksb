/* Printable prescription slip (A4 PDF): clinic header, doctor name and council registration number,
 * patient, medicine table, advice and signature line. jsPDF loads only when someone taps the button. */

export const rxPdfName = (patient) =>
  `prescription-${String((patient && patient.name) || "patient").trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "patient"}.pdf`;

const todayText = (d = new Date()) => `${String(d.getDate()).padStart(2, "0")}/${String(d.getMonth() + 1).padStart(2, "0")}/${d.getFullYear()}`;

export const buildPrescriptionPdf = async (patient = {}, profile = {}, { date = todayText() } = {}) => {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const L = 15, R = 195;
  let y = 20;
  const text = (s, x, opts = {}) => doc.text(String(s ?? ""), x, y, opts);

  doc.setTextColor(0, 0, 0);
  doc.setFont("helvetica", "bold"); doc.setFontSize(16);
  text(profile.name || "Dental Clinic", L);
  doc.setFontSize(10);
  text("PRESCRIPTION", R, { align: "right" });
  y += 6; doc.setFont("helvetica", "normal"); doc.setFontSize(9);
  const doctor = [profile.drName, profile.qualification].filter(Boolean).join(", ");
  [doctor, profile.councilRegNumber ? `Dental Council Reg. No: ${profile.councilRegNumber}` : "", profile.address,
    [profile.phone, profile.email].filter(Boolean).join("  ")]
    .filter(Boolean).forEach((s) => { text(s, L); y += 4.5; });
  y += 1; doc.line(L, y, R, y); y += 7;

  doc.setFontSize(10); doc.setFont("helvetica", "bold");
  text(`Patient: ${patient.name || ""}`, L);
  doc.setFont("helvetica", "normal");
  text(`Date: ${date}`, R, { align: "right" });
  y += 5;
  const meta = [patient.age ? `Age: ${patient.age}` : "", patient.gender ? `Sex: ${patient.gender}` : "", patient.phone ? `Phone: ${patient.phone}` : ""].filter(Boolean).join("    ");
  if (meta) { text(meta, L); y += 5; }
  y += 3;

  doc.setFont("helvetica", "bold"); doc.setFontSize(18); text("Rx", L); y += 8;
  doc.setFontSize(9);
  const cols = { n: L, med: L + 8, dose: 100, freq: 125, dur: 150, ins: 172 };
  text("#", cols.n); text("Medicine", cols.med); text("Dose", cols.dose); text("Times", cols.freq); text("For", cols.dur);
  y += 2; doc.line(L, y, R, y); y += 5;

  doc.setFont("helvetica", "normal");
  const rx = (patient.prescriptions || []).filter((p) => p && typeof p === "object");
  if (rx.length === 0) { text("No medicines prescribed.", L); y += 6; }
  rx.forEach((p, i) => {
    if (y > 255) { doc.addPage(); y = 20; }
    doc.setFont("helvetica", "bold"); text(i + 1, cols.n); text(doc.splitTextToSize(String(p.drug || ""), 88)[0], cols.med);
    doc.setFont("helvetica", "normal");
    text(String(p.dosage || "").slice(0, 14), cols.dose); text(String(p.frequency || "").slice(0, 14), cols.freq); text(String(p.duration || "").slice(0, 12), cols.dur);
    y += 4.5;
    const sub = [p.generic, p.instruction].filter(Boolean).join("  -  ");
    if (sub) { doc.setFontSize(8); doc.splitTextToSize(sub, 170).forEach((s) => { text(s, cols.med); y += 3.8; }); doc.setFontSize(9); }
    y += 3;
  });

  y = Math.max(y + 18, 235); if (y > 270) { doc.addPage(); y = 240; }
  doc.line(R - 60, y, R, y); y += 5;
  doc.setFontSize(9); text(profile.drName || "Doctor", R, { align: "right" });
  if (profile.councilRegNumber) { y += 4.5; text(`Reg. No: ${profile.councilRegNumber}`, R, { align: "right" }); }
  y += 10; doc.setFontSize(8);
  text("Computer generated by MeriDent. Take medicines as advised. Contact the clinic if you have any problem.", L);
  return doc;
};

export const downloadPrescriptionPdf = async (patient, profile, opts) => {
  const doc = await buildPrescriptionPdf(patient, profile, opts);
  doc.save(rxPdfName(patient));
};
