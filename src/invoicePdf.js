import { formatINR, invoiceLines, paidPaise, balancePaise, normalizeInvoice } from "./billing.js";

const money = (p) => `Rs. ${formatINR(p)}`;

export const invoicePdfName = (inv, receipt) =>
  `${receipt ? "receipt" : "invoice"}-${String(inv.id || "bill").replace(/[^a-zA-Z0-9_-]+/g, "-")}.pdf`;

/** Builds a real PDF file (black on white). jsPDF loads only when someone taps PDF. */
export const buildInvoicePdf = async (rawInv, profile = {}, { receipt = false } = {}) => {
  const { jsPDF } = await import("jspdf");
  const inv = normalizeInvoice(rawInv);
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const L = 15, R = 195;
  let y = 20;
  const text = (s, x, opts = {}) => doc.text(String(s ?? ""), x, y, opts);
  const row = (left, right, bold) => {
    doc.setFont("helvetica", bold ? "bold" : "normal");
    const wrapped = doc.splitTextToSize(String(left ?? ""), 120);
    text(wrapped, L);
    text(right, R, { align: "right" });
    y += 6 * wrapped.length;
    if (y > 270) { doc.addPage(); y = 20; }
  };

  doc.setTextColor(0, 0, 0);
  doc.setFont("helvetica", "bold"); doc.setFontSize(16);
  text(profile.name || "Dental Clinic", L);
  doc.setFontSize(11);
  text(receipt ? "PAYMENT RECEIPT" : "TAX INVOICE", R, { align: "right" });
  y += 6; doc.setFont("helvetica", "normal"); doc.setFontSize(9);
  [profile.tagline, profile.address, [profile.phone, profile.email].filter(Boolean).join("  "), profile.regNumber ? `Reg: ${profile.regNumber}` : ""]
    .filter(Boolean).forEach((s) => { text(s, L); y += 4.5; });
  doc.setFont("helvetica", "bold"); doc.setFontSize(10);
  doc.text(String(inv.id), R, 26, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.text(String(inv.date || ""), R, 31, { align: "right" });
  y += 2; doc.line(L, y, R, y); y += 8;

  doc.setFontSize(10);
  doc.setFont("helvetica", "bold"); text("Billed to", L); y += 6;
  doc.setFont("helvetica", "normal"); text(inv.patient || "", L); y += 9;

  doc.setFont("helvetica", "bold"); text("Treatments", L); y += 6;
  invoiceLines(inv).forEach((l) => row(l.description, money(l.amountP)));
  y += 3; doc.line(L, y, R, y); y += 6;

  row("Amount", money(inv.subtotalP));
  if (inv.discountP > 0) row("Discount", `- ${money(inv.discountP)}`);
  row("Taxable value", money(inv.taxableP));
  if (inv.gstRate > 0) {
    row(`CGST @ ${inv.gstRate / 2}%`, money(inv.cgstP));
    row(`SGST @ ${inv.gstRate / 2}%`, money(inv.sgstP));
  } else row("GST", "Exempt (therapeutic dental service)");
  doc.setFontSize(12); row("Total", money(inv.totalP), true); doc.setFontSize(10);
  y += 4;

  doc.setFont("helvetica", "bold"); text("Payments received", L); y += 6;
  const pays = (inv.payments || []).filter((p) => p && typeof p === "object");
  if (pays.length === 0) row("No payments yet", "");
  pays.forEach((p) => row(`${p.date || ""} - ${p.mode || ""}`, money(p.amountP || 0)));
  row("Paid", money(paidPaise(inv)), true);
  row("Balance due", money(balancePaise(inv)), true);

  y += 6; doc.setFont("helvetica", "normal"); doc.setFontSize(8);
  if (profile.texts && profile.texts.invoiceFooter) {
    doc.splitTextToSize(String(profile.texts.invoiceFooter), 180).forEach((s) => { text(s, L); y += 4; });
    y += 2;
  }
  text("Computer generated by MeriDent. Therapeutic dental services are exempt from GST; cosmetic services attract 18% GST.", L);
  return doc;
};

export const downloadInvoicePdf = async (inv, profile, opts = {}) => {
  const doc = await buildInvoicePdf(inv, profile, opts);
  doc.save(invoicePdfName(inv, !!opts.receipt));
};
